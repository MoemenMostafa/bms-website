let currentLang = localStorage.getItem('bms_lang') || 'en';

const seoTitles = {
  en: 'Bayern Marketing Solutions | Creative Marketing Agency',
  de: 'Bayern Marketing Solutions | Kreativagentur für Marketing',
  ar: 'Bayern Marketing Solutions | وكالة تسويق إبداعية'
};
const seoDescs = {
  en: 'German precision meets local insight — strategy, branding, performance, and social media that make your brand impossible to ignore.',
  de: 'Deutsche Präzision trifft lokales Gespür – Strategie, Branding, Performance und Social Media, die Ihre Marke unübersehbar machen.',
  ar: 'دقة ألمانية تلتقي بفهم محلي — استراتيجية وعلامة تجارية وأداء ووسائل تواصل تجعل علامتك لا يمكن تجاهلها.'
};
const ogLocales = { en: 'en_US', de: 'de_DE', ar: 'ar_SA' };

function applyLang(lang) {
  const t = translations[lang];
  if (!t) return;
  currentLang = lang;
  localStorage.setItem('bms_lang', lang);

  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.body.classList.toggle('rtl-active', lang === 'ar');

  document.title = seoTitles[lang] || seoTitles.en;
  document.querySelector('meta[name="description"]')?.setAttribute('content', seoDescs[lang] || seoDescs.en);
  document.querySelector('meta[property="og:title"]')?.setAttribute('content', seoTitles[lang] || seoTitles.en);
  document.querySelector('meta[property="og:description"]')?.setAttribute('content', seoDescs[lang] || seoDescs.en);
  document.querySelector('meta[property="og:locale"]')?.setAttribute('content', ogLocales[lang] || 'en_US');

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (!t[key]) return;
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = t[key];
    } else if (el.tagName === 'OPTION') {
      el.textContent = t[key];
    } else {
      el.innerHTML = t[key].replace(/\n/g, '<br>');
    }
  });

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

function initLang() {
  applyLang(currentLang);
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => applyLang(btn.dataset.lang));
  });
}

/* ─── Navbar ─── */
function initNav() {
  const navbar = document.getElementById('navbar');
  const hamburger = document.getElementById('hamburger');
  const mobileMenu = document.getElementById('mobile-menu');
  const mobileClose = document.getElementById('mobile-close');

  const onScroll = () => navbar.classList.toggle('scrolled', window.scrollY > 40);
  onScroll();
  window.addEventListener('scroll', onScroll, { passive: true });

  hamburger.addEventListener('click', () => {
    hamburger.classList.toggle('open');
    mobileMenu.classList.toggle('open');
    document.body.style.overflow = mobileMenu.classList.contains('open') ? 'hidden' : '';
  });

  if (mobileClose) mobileClose.addEventListener('click', closeMobile);
  mobileMenu.querySelectorAll('a').forEach(a => a.addEventListener('click', closeMobile));

  function closeMobile() {
    hamburger.classList.remove('open');
    mobileMenu.classList.remove('open');
    document.body.style.overflow = '';
  }
}

